def apply_review(concepts,relations,rules):
    if not any(c[0]=='Срок службы' for c in concepts):
        concepts.append(('Срок службы','Свойства',['долговечность','расчётный срок эксплуатации'],'Продолжительность эксплуатации при заданных условиях обслуживания. Учебное значение не является гарантией производителя.'))
    links=[]
    for name in sorted(set(PRODUCT_CONCEPT.values())):
        for attr in ['Плотность','Теплопроводность','Срок службы']:
            links.append((name,'обладает_свойством',attr))
    links.extend([('Керамический кирпич','обладает_свойством','Прочность на сжатие'),('Газобетон','обладает_свойством','Прочность на сжатие'),('Пенополиуретан','является','Утеплитель')])
    for link in links:
        if link not in relations: relations.append(link)
    # Numeric weights and conditions are deliberately unchanged in this review.
    rules[:]=[r[:-1]+(EXPLANATIONS.get(r[0],r[-1]),) for r in rules]

def rule_note(rule):
    code,conditions,then,cf,explanation=rule
    refs=[]
    if code in {'R40','R43','R44','R45','R46','R47'}: refs=['knauf']
    elif code in {'R53','R54','R55','R84','R85'}: refs=['foundation']
    elif code in {'R90','R91'}: refs=['xps']
    return dict(kind='Допущение модели' if then[0]=='fact' else 'Авторская эвристика',
        basis='Правило задано в учебной базе проекта; технические ссылки поясняют контекст, но не задают его вес.',
        cf_basis='CF назначен автором учебной модели. Он не измерен на выборке, не откалиброван и не является вероятностью или нормативным коэффициентом.',
        source_label='Исходные условия и заключение в data/knowledge.py',source_url=RULES_URL,
        references=[REFERENCES[key] for key in refs],checked_at='2026-11-21')

def property_records(products):
    out=[]
    for p in products:
        if p['id'] in CATALOG_ISSUES: continue
        concept=PRODUCT_CONCEPT.get(p['id'])
        if not concept: continue
        for field,(label,unit) in DEFINITIONS.items():
            value=p.get(field)
            if value is None: continue
            out.append(dict(product_id=p['id'],product=p['name'],concept=concept,attribute=field,label=label,value=value,unit=unit,
                source_kind='Учебный каталог',source_url=CATALOG_URL,
                conditions='Условия измерения и паспорт изделия не указаны. Значение учебное; не использовать как проектную характеристику.'))
    return out
